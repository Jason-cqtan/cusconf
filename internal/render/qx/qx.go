// Name makes a node/group name safe in Quantumult X's comma-separated syntax.
var Name = surge.Name

// policy maps a profile policy to a Quantumult X policy name.
func policy(p string) string {
	switch strings.ToUpper(p) {
	case "DIRECT":
		return "direct"
	case "REJECT":
		return "reject"
	}
	return Name(p)
}

var ruleType = map[string]string{
	"DOMAIN": "host", "DOMAIN-SUFFIX": "host-suffix", "DOMAIN-KEYWORD": "host-keyword", "DOMAIN-WILDCARD": "host-wildcard",
	"IP-CIDR": "ip-cidr", "IP-CIDR6": "ip6-cidr", "GEOIP": "geoip", "USER-AGENT": "user-agent", "IP-ASN": "ip-asn",
}

func Render(c *render.Config) render.Result {
	var w render.Warnings
	var b strings.Builder
	g := c.General
	fmt.Fprintf(&b, "# Generated by cusconf for %s\n", c.Target)
	if c.ManagedURL != "" {
		fmt.Fprintf(&b, "# Subscription: %s\n", c.ManagedURL)
	}

	b.WriteString("\n[general]\n")
	b.WriteString(general(g))

	b.WriteString("\n[dns]\n")
	b.WriteString(dns(g, &w))

	var servers []string
	kept := map[string]bool{}
	for _, n := range c.Nodes {
		line, err := serverLine(c, n)
		if err != nil {
			w.Add("node", n.Name, "%v", err)
			continue
		}
		kept[n.Name] = true
		servers = append(servers, line)
	}

	groups := render.FinalizeGroups(c.Groups, kept, &w)
	b.WriteString("\n[policy]\n")
	for i := range groups {
		b.WriteString(policyLine(c, &groups[i], &w) + "\n")
	}

	var local, remote []string
	finalLine := ""
	sawRemote, warnedOrder := false, false
	for _, r := range c.Rules {
		pol := policy(r.Policy)
		comments := ""
		for _, l := range r.CommentLines() {
			comments += "# " + l + "\n"
		}
		switch r.Type {
		case "FINAL", "MATCH":
			finalLine = comments + "final, " + pol
			continue
		case "RULE-SET":
			rs := c.RuleSets[r.Value]
			u, _ := c.RuleSetURL(rs, "", "qx")
			if u == "" {
				w.Add("rule", r.Value, "Quantumult X needs the rule mirror to convert rule sets; skipped")
				continue
			}
			sawRemote = true
			remote = append(remote, fmt.Sprintf("%s%s, tag=%s, force-policy=%s, update-interval=%d, opt-parser=false, enabled=true",
				comments, u, Name(rs.Name), pol, or0(rs.Interval, 86400)))
			continue
		}
		t, ok := ruleType[strings.ToUpper(r.Type)]
		if !ok {
			w.Add("rule", r.Type+","+r.Value, "rule type %s not supported by Quantumult X; skipped", r.Type)
			continue
		}
		if sawRemote && !warnedOrder {
			warnedOrder = true
			w.Add("rule", r.Type+","+r.Value, "Quantumult X keeps [filter_remote] and [filter_local] apart; rules after a rule set no longer keep their position")
		}
		v := r.Value
		if t == "geoip" {
			v = strings.ToLower(v)
		}
		local = append(local, fmt.Sprintf("%s%s, %s, %s", comments, t, v, pol))
	}
	if finalLine == "" {
		final := render.FirstGroup(groups)
		w.Add("rule", "FINAL", "no FINAL rule; added final, %s", final)
		finalLine = "final, " + policy(final)
	}
	local = append(local, finalLine)

	b.WriteString("\n[server_remote]\n")
	b.WriteString("\n[filter_remote]\n")
	for _, l := range remote {
		b.WriteString(l + "\n")
	}
	b.WriteString("\n[rewrite_remote]\n")
	b.WriteString("\n[server_local]\n")
	for _, l := range servers {
		b.WriteString(l + "\n")
	}
	b.WriteString("\n[filter_local]\n")
	for _, l := range local {
		b.WriteString(l + "\n")
	}
	b.WriteString("\n[rewrite_local]\n\n[mitm]\n")
	return render.Result{Content: b.String(), ContentType: "text/plain; charset=utf-8", Warnings: w}
}

func or(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

func or0(a, b int) int {
	if a > 0 {
		return a
	}
	return b
}

func general(g profile.General) string {
	lines := []render.KV{
		{K: "server_check_url", V: or(g.TestURL, render.DefaultTestURL)},
		{K: "network_check_url", V: or(g.InternetTestURL, "http://www.apple.com/library/test/success.html")},
		{K: "server_check_timeout", V: "3000"},
		{K: "dns_exclusion_list", V: "*.cmpassport.com, *.jegotrip.com.cn, *.icitymobile.mobi, id6.me"},
		{K: "excluded_routes", V: "239.255.255.250/32, 24.105.30.129/32, 185.60.218.50/32, 185.60.216.50/32, 137.135.129.174/32"},
	}
	if len(g.SkipProxy) > 0 {
		lines = append(lines, render.KV{K: "skip_proxy", V: strings.Join(g.SkipProxy, ", ")})
	}
	return render.MergeKV(lines, g.Extra["qx"], "=")
}

func dns(g profile.General, w *render.Warnings) string {
	var b strings.Builder
	if !g.IPv6 {
		b.WriteString("no-ipv6\n")
	}
	servers := g.DNS
	if len(servers) == 0 {
		servers = []string{"system", "223.5.5.5", "119.29.29.29"}
	}
	system := false
	for _, s := range servers {
		switch {
		case s == "system":
			system = true
		case strings.HasPrefix(s, "https://"):
			fmt.Fprintf(&b, "doh-server=%s\n", s)
		case strings.HasPrefix(s, "quic://"):
			fmt.Fprintf(&b, "doq-server=%s\n", s)
		default:
			fmt.Fprintf(&b, "server=%s\n", s)
		}
	}
	if !system {
		b.WriteString("no-system\n")
	}
	for _, h := range g.Hosts {
		if strings.Contains(h.Domain, ":") {
			w.Add("host", h.Domain, "rule-set based host entries are Surge-only; skipped")
			continue
		}
		d := h.Domain
		switch h.Kind() {
		case "ip":
			for _, ip := range h.IPs() {
				fmt.Fprintf(&b, "address=/%s/%s\n", d, ip)
			}
		case "server":
			for _, s := range strings.Split(strings.TrimPrefix(h.Value, "server:"), ",") {
				s = strings.TrimSpace(s)
				fmt.Fprintf(&b, "server=/%s/%s\n", d, s)
			}
		default:
			fmt.Fprintf(&b, "alias=/%s/%s\n", d, h.Value)
		}
	}
	return b.String()
}

type params struct{ parts []string }

func (p *params) add(k, v string) {
	if v != "" {
		p.parts = append(p.parts, k+"="+v)
	}
}

func (p *params) flag(k string, v bool) {
	if v {
		p.parts = append(p.parts, k+"=true")
	}
}

func hostPort(h string, port int) string {
	if strings.Contains(h, ":") {
		return fmt.Sprintf("[%s]:%d", h, port)
	}
	return fmt.Sprintf("%s:%d", h, port)
}

func serverLine(c *render.Config, n *node.Node) (string, error) {
	feat := "proxy." + string(n.Type)
	if n.Type == node.TUIC && n.Version == 5 {
		feat = "proxy.tuic-v5"
	}
	if !c.Has(feat) {
		return "", fmt.Errorf("%s %s", n.Type, c.Req(feat))
	}
	var p params
	kind := string(n.Type)
	switch n.Type {
	case node.SS:
		kind = "shadowsocks"
		p.add("method", n.Cipher)
		p.add("password", n.Password)
		switch n.Plugin {
		case "":
		case "obfs":
			p.add("obfs", n.PluginOpts["mode"])
			p.add("obfs-host", n.PluginOpts["host"])
			p.add("obfs-uri", n.PluginOpts["path"])
		case "v2ray-plugin":
			mode := "ws"
			if n.PluginOpts["tls"] == "true" {
				mode = "wss"
			}
			p.add("obfs", mode)
			p.add("obfs-host", n.PluginOpts["host"])
			p.add("obfs-uri", n.PluginOpts["path"])
		default:
			return "", fmt.Errorf("ss plugin %q not supported by Quantumult X", n.Plugin)
		}
	case node.SSR:
		kind = "shadowsocks"
		p.add("method", n.Cipher)
		p.add("password", n.Password)
		p.add("ssr-protocol", n.Protocol)
		p.add("ssr-protocol-param", n.ProtocolParam)
		p.add("obfs", n.Obfs)
		p.add("obfs-host", n.ObfsParam)
	case node.VMess, node.VLESS:
		if n.Type == node.VMess {
			m := n.Cipher
			switch m {
			case "aes-128-gcm", "chacha20-ietf-poly1305", "none":
			default:
				m = "chacha20-ietf-poly1305"
			}
			p.add("method", m)
		} else {
			if n.Cipher != "" && n.Cipher != "none" {
				return "", fmt.Errorf("VLESS encryption %s", c.Req("vless.encryption"))
			}
			p.add("method", "none")
		}
		p.add("password", n.UUID)
		if err := obfs(c, n, &p); err != nil {
			return "", err
		}
		if n.Type == node.VLESS {
			p.add("vless-flow", n.Flow)
		}
	case node.Trojan:
		p.add("password", n.Password)
		if n.TransportType() == "tcp" {
			p.add("over-tls", "true")
			tlsParams(c, n, &p)
		} else if err := obfs(c, n, &p); err != nil {
			return "", err
		}
	case node.HTTP, node.SOCKS5:
		p.add("username", n.Username)
		p.add("password", n.Password)
		if n.TLSEnabled() {
			p.add("over-tls", "true")
			tlsParams(c, n, &p)
		}
	default:
		return "", fmt.Errorf("%s not supported by Quantumult X", n.Type)
	}
	if n.TLS.Reality() {
		if !c.Has("tls.reality") || n.Type != node.VLESS {
			return "", fmt.Errorf("REALITY %s", c.Req("tls.reality"))
		}
		p.add("reality-base64-pubkey", n.TLS.RealityPubKey)
		p.add("reality-hex-shortid", n.TLS.RealityShortID)
	}
	p.flag("fast-open", n.TFO)
	if n.Type != node.HTTP {
		if n.UDP != nil {
			p.add("udp-relay", fmt.Sprint(*n.UDP))
		}
	}
	p.add("tag", Name(n.Name))
	return kind + "=" + hostPort(n.Server, n.Port) + ", " + strings.Join(p.parts, ", "), nil
}

// obfs writes the transport of vmess / vless / trojan: ws, wss or over-tls.
func obfs(c *render.Config, n *node.Node, p *params) error {
	t := n.TransportType()
	if t != "tcp" && !c.Has("transport."+t) {
		return fmt.Errorf("transport %s %s", t, c.Req("transport."+t))
	}
	tls := n.TLSEnabled()
	switch t {
	case "tcp":
		if tls {
			p.add("obfs", "over-tls")
			p.add("obfs-host", n.TLS.SNI)
		}
	case "ws":
		if tls {
			p.add("obfs", "wss")
		} else {
			p.add("obfs", "ws")
		}
		p.add("obfs-host", or(n.Transport.Host, sni(n)))
		p.add("obfs-uri", n.Transport.Path)
	default:
		return fmt.Errorf("transport %s not supported by Quantumult X", t)
	}
	if tls {
		if s := sni(n); s != "" && t == "ws" && s != n.Transport.Host {
			p.add("tls-host", s)
		}
		if n.TLS.SkipVerify {
			p.add("tls-verification", "false")
		}
	}
	return nil
}

func sni(n *node.Node) string {
	if n.TLS == nil {
		return ""
	}
	return n.TLS.SNI
}

func tlsParams(c *render.Config, n *node.Node, p *params) {
	if n.TLS == nil {
		return
	}
	p.add("tls-host", n.TLS.SNI)
	if n.TLS.SkipVerify {
		p.add("tls-verification", "false")
	}
	if len(n.TLS.ALPN) > 0 && c.Has("tls.alpn") {
		p.add("tls-alpn", strings.Join(n.TLS.ALPN, ","))
	}
}

func policyLine(c *render.Config, g *render.Group, w *render.Warnings) string {
	typ := render.DowngradeGroupType(c, g, w)
	kind := map[profile.GroupType]string{profile.Select: "static", profile.URLTest: "url-latency-benchmark", profile.Fallback: "available", profile.LoadBalance: "round-robin"}[typ]
	parts := []string{Name(g.Name)}
	for _, m := range g.Members {
		parts = append(parts, policy(m))
	}
	if typ == profile.URLTest {
		parts = append(parts, fmt.Sprintf("check-interval=%d", or0(g.Interval, 600)), fmt.Sprintf("tolerance=%d", or0(g.Tolerance, 100)))
	}
	if g.Icon != "" && c.Has("group.icon") {
		parts = append(parts, "img-url="+g.Icon)
	}
	return kind + "=" + strings.Join(parts, ", ")
}
